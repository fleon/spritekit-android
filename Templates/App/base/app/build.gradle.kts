// Every staging task runs before AGP merges the asset folders.
tasks.withType<com.android.build.gradle.tasks.MergeSourceSetFolders>().configureEach {
    dependsOn(stageFonts, stageAudio, stageLevelAssets, stageStrings)
}
tasks.matching { it.name.contains("lint", ignoreCase = true) }.configureEach {
    dependsOn(stageFonts, stageAudio, stageLevelAssets, stageStrings)
}

// An APK with no Swift in it still installs and launches — and then dies in
// the linker. Fail here instead.
val checkNativeLibraries = tasks.register("checkNativeLibraries") {
    val jniLibs = layout.projectDirectory.dir("src/main/jniLibs")
    doFirst {
        val missing = abis.filter { !jniLibs.dir(it).file("libAndroidShell.so").asFile.exists() }
        if (missing.isNotEmpty()) {
            throw GradleException(
                "No libAndroidShell.so for ${missing.joinToString(", ")}.\n" +
                    "Build the native side first:\n" +
                    "    Android/Scripts/build-sdl.sh <abi> && Android/Scripts/build-shell.sh --debug <abi>"
            )
        }
    }
}
// The art is packed by a script, not by Gradle: say so rather than ship an
// APK whose every texture is the white placeholder.
val checkArt = tasks.register("checkArt") {
    val index = rootProject.file("../Assets/index.json")
    doFirst {
        if (!index.exists()) throw GradleException(
            "No Android/Assets/index.json: pack the art first (Android/README.md):\n" +
                "    node Android/spritekit-android/Tools/guard.js 12 -- node Android/spritekit-android/Tools/Art/xcassets-art.js Android/Assets Assets/Assets.xcassets"
        )
    }
}
tasks.named("preBuild") { dependsOn(checkNativeLibraries, checkArt) }
