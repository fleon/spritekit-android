// An APK with no Swift in it still installs and launches — and then dies in
// the linker. Fail here instead.
val checkNativeLibraries = tasks.register("checkNativeLibraries") {
    val jniLibs = layout.projectDirectory.dir("src/main/jniLibs")
    doFirst {
        val missing = abis.filter { !jniLibs.dir(it).file("libAndroidShell.so").asFile.exists() }
        if (missing.isNotEmpty()) {
            throw GradleException(
                "No libAndroidShell.so for ${missing.joinToString(", ")}.\n" +
                    "Build the native side first, from the game's root:\n" +
                    "    Android/spritekit-android/Scripts/build-sdl.sh <abi> && Android/spritekit-android/Scripts/build-shell.sh --debug <abi>"
            )
        }
    }
}
// The art is packed by a script, not by Gradle: say so rather than ship an
// APK whose every texture is the white placeholder.
val checkArt = tasks.register("checkArt") {
    val index = rootProject.file("../Assets/index.json")
    doFirst {
        if (!index.exists()) throw GradleException(
            "No Android/Assets/index.json: pack the art first, from the game's root\n" +
                "(spritekit-android/README.md, \"Packing art from an asset catalog\"):\n" +
                "    node Android/spritekit-android/Tools/guard.js 12 -- node Android/spritekit-android/Tools/Art/xcassets-art.js Android/Assets Assets/Assets.xcassets"
        )
    }
}
// Both guard what goes into an APK or a bundle: its libraries and its
// assets. Not `preBuild`, which the JVM's unit tests (`testDebugUnitTest`)
// run too, and they need neither.
fun packagesApp(task: Task) = !task.name.contains("Test")
tasks.matching { it.name.startsWith("merge") && it.name.endsWith("NativeLibs") && packagesApp(it) }
    .configureEach { dependsOn(checkNativeLibraries) }
tasks.matching { it.name.startsWith("merge") && it.name.endsWith("Assets") && packagesApp(it) }
    .configureEach { dependsOn(checkArt) }
// Every release build names its beta choice.
tasks.matching { it.name == "preReleaseBuild" }.configureEach { dependsOn(checkBetaChoice) }
