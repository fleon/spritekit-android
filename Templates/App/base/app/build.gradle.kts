// Both ABIs unless `-Pgame.abis=arm64-v8a` asks for fewer: a quick build for
// the Apple Silicon emulators, which needs only that ABI's
// `Android/Scripts/build-shell.sh` run.
val abis = (findProperty("game.abis") as String?)?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }
    ?: listOf("arm64-v8a", "x86_64")

// What goes into the APK out of the repository's own `Assets`, each under a
// prefix of its own so the packed art keeps the assets root:
//
//   art      Android/Assets: index.json and the atlas pages, packed from
//            Assets/Assets.xcassets by the runtime's xcassets-art.js (see
//            Android/README.md). Gitignored.
//   fonts/   the faces in Assets/Fonts, which the shell registers at launch
//   audio/   Assets/Music and Assets/SFX, the same bytes the Apple build
//            bundles
//   levels/  the .json files at the top of Assets (and Play Games' mapping,
//            when there is one), where `Bundle.main` finds a .json
//   lproj/   each language's Localizable.strings
//
// Everything rides in the base module. A game whose base module would pass
// Play's 200 MB moves its art, fonts and audio into an install-time asset
// pack instead.
val stagedFonts = "build/generated/fontAssets"
val stageFonts = tasks.register<Sync>("stageFonts") {
    from(rootProject.file("../../Assets/Fonts")) {
        include("*.ttf", "*.otf")
        into("fonts")
    }
    into(file(stagedFonts))
}

val audioAssets = "build/generated/audioAssets"
val stageAudio = tasks.register<Sync>("stageAudio") {
    from(rootProject.file("../../Assets/Music")) { into("audio/Music") }
    from(rootProject.file("../../Assets/SFX")) { into("audio/SFX") }
    into(file(audioAssets))
}

// Play Games Services: the project's ID and the achievements' and
// leaderboards' IDs, generated by the Play tools once they exist on Play.
// The file goes into the APK beside the levels and the ID into the
// manifest's APP_ID. With no file, or no ID in it, the build has no Play
// Games: sign-in answers "no" at once and progress stays on the device.
val playGamesFile = rootProject.file("../../Tools/Play/PlayGames/PlayGamesAchievements.json")
val playGamesAppId: String = (findProperty("game.playGamesAppId") as String?)
    ?: if (playGamesFile.exists()) {
        ((groovy.json.JsonSlurper().parse(playGamesFile) as Map<*, *>)["applicationId"] as String?) ?: ""
    } else ""

val levelAssets = "build/generated/levelAssets"
val stageLevelAssets = tasks.register<Sync>("stageLevelAssets") {
    from(rootProject.file("../../Assets")) { include("*.json") }
    if (playGamesFile.exists()) from(playGamesFile)
    into(file("$levelAssets/levels"))
}

// Each language's strings, under `assets/lproj/<language>.lproj/`, as
// `Bundle.main` opens them. Only the `.strings` files: the storyboards in
// Base.lproj are Apple's alone.
val stringAssets = "build/generated/stringAssets"
val stageStrings = tasks.register<Sync>("stageStrings") {
    from(rootProject.file("../../Assets")) { include("*.lproj/*.strings") }
    into(file("$stringAssets/lproj"))
}

// The upload key, which signs what goes to Play (Play re-signs it with the
// app signing key). It lives outside every checkout and its password in the
// macOS Keychain, never in a file:
//
//     ~/.config/GAME_KEY/android/upload.jks
//     security find-generic-password -s GAME_KEY-android-upload -a upload -w
//
// CI passes both in the environment instead (GAME_UPLOAD_KEYSTORE,
// GAME_UPLOAD_PASSWORD). With neither, a release build is unsigned.
val uploadKeystore = file(System.getenv("GAME_UPLOAD_KEYSTORE")
    ?: "${System.getProperty("user.home")}/.config/GAME_KEY/android/upload.jks")
fun uploadPassword(): String? = System.getenv("GAME_UPLOAD_PASSWORD") ?: runCatching {
    providers.exec {
        commandLine("security", "find-generic-password", "-s", "GAME_KEY-android-upload", "-a", "upload", "-w")
        isIgnoreExitValue = true
    }.standardOutput.asText.get().trim().ifEmpty { null }
}.getOrNull()

// One build setting from the iOS app's Xcode project (one build number on
// every platform: Apple build = Android versionCode).
fun appleVersion(setting: String): String {
    val project = rootProject.file("../../XCODE_PROJECT.xcodeproj/project.pbxproj").readText()
    val values = Regex("""\b$setting = ([^;]+);""").findAll(project).map { it.groupValues[1].trim('"', ' ') }.toSet()
    return values.singleOrNull() ?: error("$setting isn't one value in the Xcode project: $values")
}

// The NDK, for a release build's strip and its native debug symbols.
val ndk = file(System.getenv("ANDROID_NDK_HOME") ?: "${System.getProperty("user.home")}/Library/Android/android-ndk-r30")

android {
    namespace = "PACKAGE_NAME"
    compileSdk = property("game.compileSdk").toString().toInt()

    defaultConfig {
        // The iOS bundle ID: one product on both stores.
        applicationId = "PACKAGE_NAME"
        minSdk = property("game.minSdk").toString().toInt()
        targetSdk = property("game.targetSdk").toString().toInt()
        versionCode = ((findProperty("game.versionCode") as String?) ?: appleVersion("CURRENT_PROJECT_VERSION")).toInt()
        versionName = (findProperty("game.versionName") as String?) ?: appleVersion("MARKETING_VERSION")
        ndk { abiFilters += abis }

        // Play Games' project ID, a string resource because the manifest's
        // APP_ID must name one (a bare number would be read as a float).
        resValue("string", "game_services_project_id", playGamesAppId)
        // The app's licence key from Play Console (Monetization setup), with
        // which `PlayBilling` checks Play's signature on each purchase.
        // Public, not a secret; empty skips the check.
        buildConfigField("String", "PLAY_LICENSE_KEY",
            "\"" + ((findProperty("game.playLicenseKey") as String?) ?: "") + "\"")
    }

    buildFeatures {
        buildConfig = true
        resValues = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    sourceSets {
        getByName("main") {
            assets.srcDirs("../../Assets", stagedFonts, audioAssets, levelAssets, stringAssets)
        }
    }

    androidResources {
        // Stored rather than deflated: the pages and fonts are read straight
        // out of the mapped APK, and MediaCodec decodes the soundtrack from a
        // file descriptor into the APK, which only a stored asset has.
        noCompress += listOf("png", "ktx", "json", "ttf", "otf", "m4a", "wav", "ogg", "mp3", "strings")
    }

    if (ndk.isDirectory) {
        ndkPath = ndk.path
        ndkVersion = ndk.resolve("source.properties").readLines()
            .first { it.startsWith("Pkg.Revision") }.substringAfter("=").trim()
    }

    signingConfigs {
        if (uploadKeystore.exists()) {
            create("upload") {
                storeFile = uploadKeystore
                storeType = "PKCS12"
                keyAlias = "upload"
                val password = uploadPassword()
                storePassword = password
                keyPassword = password
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("upload")
            // Native debug symbols for Play vitals' crash and ANR stacks.
            ndk { debugSymbolLevel = "FULL" }
        }
        debug {
            isJniDebuggable = true
            // `-Pgame.applicationIdSuffix=.test` installs beside another build.
            applicationIdSuffix = (findProperty("game.applicationIdSuffix") as String?) ?: ""
        }
    }
}

// A debug build's libraries come stripped from `build-shell.sh --debug`.
androidComponents {
    onVariants(selector().withBuildType("debug")) { variant ->
        variant.packaging.jniLibs.keepDebugSymbols.add("**/*.so")
    }
}

