#!/usr/bin/env python3
# Writes Sources/SpriteKitShim/ArabicJoining.swift: the Joining_Type
# (ArabicShaping.txt) of the Arabic blocks' code points and the zero-width
# joiner, other than non-joining and transparent, as sorted ranges, from the
# Mac's ICU (Python's unicodedata has no Joining_Type), so it runs on macOS.
#
#   python3 Tools/Text/arabic-joining.py
import ctypes
import os

icu = ctypes.CDLL("/usr/lib/libicucore.dylib")
value = icu.u_getIntPropertyValue
value.restype = ctypes.c_int32
value.argtypes = [ctypes.c_int32, ctypes.c_int32]
version = (ctypes.c_uint8 * 4)()
icu.u_getUnicodeVersion(version)
JOINING_TYPE = 0x1007
# U_JT_JOIN_CAUSING, U_JT_DUAL_JOINING, U_JT_LEFT_JOINING, U_JT_RIGHT_JOINING
names = {1: "causing", 2: "dual", 3: "left", 4: "right"}
BLOCKS = [(0x0600, 0x06FF), (0x0750, 0x077F), (0x0870, 0x08FF), (0x200D, 0x200D)]

ranges = []
for first, last in BLOCKS:
    previous, start = None, first
    for c in range(first, last + 2):
        found = names.get(value(c, JOINING_TYPE)) if c <= last else None
        if found != previous:
            if previous is not None:
                ranges.append((start, c - 1, previous))
            previous, start = found, c

unicode = "%d.%d.%d" % (version[0], version[1], version[2])
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
path = os.path.join(root, "Sources/SpriteKitShim/ArabicJoining.swift")
with open(path, "w") as out:
    out.write("#if SPRITEKIT_SHIM\n")
    out.write("// Generated by Tools/Text/arabic-joining.py from Unicode %s: don't edit.\n\n" % unicode)
    out.write("extension Kashida {\n")
    out.write("    /// The Arabic blocks' joining code points and the zero-width joiner,\n")
    out.write("    /// as (first, last, joining type), sorted.\n")
    out.write("    static let joiningRanges: [(UInt32, UInt32, Joining)] = [\n")
    for first, last, found in ranges:
        out.write("        (0x%04X, 0x%04X, .%s),\n" % (first, last, found))
    out.write("    ]\n}\n#endif\n")
print("%d ranges, Unicode %s -> %s" % (len(ranges), unicode, os.path.relpath(path, root)))
