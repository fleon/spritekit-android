#!/usr/bin/env python3
# Writes Sources/SpriteKitShim/BidiClasses.swift: every code point's
# Bidi_Class (UAX #9) other than L, as sorted ranges, from Python's
# unicodedata. Unassigned code points take the default UAX #9 gives their
# block (R in the Hebrew and other right-to-left blocks, AL in the Arabic
# ones, L elsewhere).
#
#   python3 Tools/Text/bidi-classes.py
import os
import unicodedata

RIGHT = [(0x0590, 0x05FF), (0x07C0, 0x085F), (0xFB1D, 0xFB4F), (0x10800, 0x10FFF), (0x1E800, 0x1EFFF)]
ARABIC = [(0x0600, 0x07BF), (0x0860, 0x08FF), (0xFB50, 0xFDCF), (0xFDF0, 0xFDFF), (0xFE70, 0xFEFF), (0x1EC70, 0x1EFFF)]


def bidi_class(c):
    found = unicodedata.bidirectional(chr(c))
    if found:
        return found
    if any(a <= c <= b for a, b in ARABIC):
        return "AL"
    if any(a <= c <= b for a, b in RIGHT):
        return "R"
    return "L"


ranges = []
previous, start = None, 0
for c in range(0x110000):
    found = bidi_class(c)
    if found != previous:
        if previous not in (None, "L"):
            ranges.append((start, c - 1, previous))
        previous, start = found, c
if previous != "L":
    ranges.append((start, 0x10FFFF, previous))

names = {"L": "l", "R": "r", "AL": "al", "EN": "en", "ES": "es", "ET": "et", "AN": "an", "CS": "cs",
         "NSM": "nsm", "BN": "bn", "B": "b", "S": "s", "WS": "ws", "ON": "on", "LRE": "lre", "LRO": "lro",
         "RLE": "rle", "RLO": "rlo", "PDF": "pdf", "LRI": "lri", "RLI": "rli", "FSI": "fsi", "PDI": "pdi"}
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
path = os.path.join(root, "Sources/SpriteKitShim/BidiClasses.swift")
with open(path, "w") as out:
    out.write("#if SPRITEKIT_SHIM\n")
    out.write("// Generated by Tools/Text/bidi-classes.py from Unicode %s: don't edit.\n\n" % unicodedata.unidata_version)
    out.write("extension Bidi {\n")
    out.write("    /// Every code point whose Bidi_Class isn't L, as (first, last, class), sorted.\n")
    out.write("    static let classRanges: [(UInt32, UInt32, BidiClass)] = [\n")
    for first, last, found in ranges:
        out.write("        (0x%04X, 0x%04X, .%s),\n" % (first, last, names[found]))
    out.write("    ]\n}\n#endif\n")
print("%d ranges, Unicode %s -> %s" % (len(ranges), unicodedata.unidata_version, os.path.relpath(path, root)))
