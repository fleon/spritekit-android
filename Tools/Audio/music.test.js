'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const lib = require('./lib');

function gameDir(settings) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'music-test-'));
  const dir = path.join(root, 'Tools', 'Audio');
  fs.mkdirSync(path.join(dir, 'Masters'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'music.json'), JSON.stringify(settings));
  return { root, dir };
}

test('settings resolve against the root, tracks in order', () => {
  const { root, dir } = gameDir({ tracks: { 'Title Theme': 'MusicTitle', Game: { resource: 'MusicGame', minLoopSeconds: 90 } } });
  const settings = lib.readSettings(dir);
  assert.strictEqual(settings.root, root);
  assert.strictEqual(settings.output, path.join(root, 'Assets/Music'));
  assert.strictEqual(settings.swift, path.join(root, 'Source/Utils/MusicLoops.swift'));
  assert.deepStrictEqual(settings.tracks, [
    { master: 'Title Theme', resource: 'MusicTitle', minLoopSeconds: 0 },
    { master: 'Game', resource: 'MusicGame', minLoopSeconds: 90 },
  ]);
});

test('settings refuse missing tracks, bad names and two tracks on one resource', () => {
  assert.throws(() => lib.readSettings(gameDir({}).dir), /lists no tracks/);
  assert.throws(() => lib.readSettings(gameDir({ tracks: { A: 'Music A' } }).dir), /resource name/);
  assert.throws(() => lib.readSettings(gameDir({ tracks: { A: 'M', B: 'M' } }).dir), /Two tracks export to M/);
  assert.throws(() => lib.readSettings(gameDir({ tracks: { A: { resource: 'M', minLoopSeconds: -1 } } }).dir), /minLoopSeconds/);
});

test('a master is found by any listed extension, WAV first', () => {
  const { dir } = gameDir({ tracks: { Song: 'MusicSong' } });
  const settings = lib.readSettings(dir);
  assert.throws(() => lib.masterFile(settings, 'Song'), /Missing master "Song"/);
  fs.writeFileSync(path.join(dir, 'Masters', 'Song.mp3'), 'ID3');
  assert.strictEqual(path.basename(lib.masterFile(settings, 'Song')), 'Song.mp3');
  fs.writeFileSync(path.join(dir, 'Masters', 'Song.wav'), 'version https://git-lfs.github.com/spec/v1\n');
  assert.strictEqual(path.basename(lib.masterFile(settings, 'Song')), 'Song.wav');
  assert.ok(lib.isLfsPointer(lib.masterFile(settings, 'Song')));
});

test('a WAV round-trips through writeFloatWav and readWav', () => {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'music-test-')), 'a.wav');
  const samples = [Float32Array.from([0, 0.5, -0.25]), Float32Array.from([1, -1, 0.125])];
  lib.writeFloatWav(file, 48000, samples);
  const read = lib.readWav(file);
  assert.strictEqual(read.sampleRate, 48000);
  assert.strictEqual(read.frames, 3);
  assert.deepStrictEqual(read.samples, samples);
});

test('the crossfade keeps equal gain for correlated audio and equal power for uncorrelated', () => {
  for (const t of [0.1, 0.5, 0.9]) {
    const [outGain, inGain] = lib.crossfadeGains(t, 1);
    assert.ok(Math.abs(outGain + inGain - 1) < 1e-9);
    const [outPower, inPower] = lib.crossfadeGains(t, 0);
    assert.ok(Math.abs(outPower * outPower + inPower * inPower - 1) < 1e-9);
  }
  assert.deepStrictEqual(lib.crossfadeGains(1, 0).map((g) => Math.round(g * 1e9) / 1e9), [0, 1]);
});

test('the cut ends on the loop start\'s audio, crossfaded, and runs on past the loop end', () => {
  const frames = 20000;
  const channel = Float32Array.from({ length: frames }, (_, i) => i);
  const loop = { loopStart: 100, loopEnd: 10000, crossfadeFrames: 4, crossfadeCorrelation: 1 };
  const [cut] = lib.cutLoop([channel], loop);
  assert.strictEqual(cut.length, loop.loopEnd + lib.TAIL_FRAMES);
  assert.strictEqual(cut[loop.loopEnd - 5], loop.loopEnd - 5);
  // The last frame before the loop end is the frame before the loop start.
  assert.ok(Math.abs(cut[loop.loopEnd - 1] - (loop.loopStart - 1)) < 1e-3);
  assert.strictEqual(cut[loop.loopEnd], loop.loopStart);
  assert.strictEqual(cut[loop.loopEnd + lib.TAIL_FRAMES - 1], loop.loopStart + lib.TAIL_FRAMES - 1);
});

test('a loop that no longer fits its master is refused', () => {
  const loop = { loopStart: 48000, loopEnd: 480000, crossfadeFrames: 1920, masterFrames: 500000, sampleRate: 48000 };
  assert.strictEqual(lib.loopProblem('Song', loop, 500000, 48000), null);
  assert.match(lib.loopProblem('Song', undefined, 500000, 48000), /No loop for "Song"/);
  assert.match(lib.loopProblem('Song', loop, 500001, 48000), /changed since its loop was found/);
  assert.match(lib.loopProblem('Song', { ...loop, loopEnd: 52000 }, 500000, 48000), /Bad loop points/);
});

test('the Swift file lists each track\'s loop as a MusicLoop', () => {
  const source = lib.swiftSource([{ resource: 'MusicTitle', loop: { loopStart: 10, loopEnd: 20 } }]);
  assert.match(source, /^\/\/ Generated by/);
  assert.match(source, /import PlatformAudio/);
  assert.match(source, /"MusicTitle": MusicLoop\(start: 10, end: 20\),/);
});

test('a medley track keeps its recipe, and a bad one is refused', () => {
  const medley = { bpm: 120, parts: [{ master: 'A', firstDownbeat: 0, from: 1, to: 3 }, { master: 'B', firstDownbeat: 0, from: 1, to: 2 }] };
  const settings = lib.readSettings(gameDir({ tracks: { Game: { resource: 'MusicGame', medley } } }).dir);
  assert.deepStrictEqual(settings.tracks, [{ master: 'Game', resource: 'MusicGame', minLoopSeconds: 0, medley }]);
  const refused = (m) => assert.throws(() => lib.readSettings(gameDir({ tracks: { Game: { resource: 'MusicGame', medley: m } } }).dir), /medley/);
  refused({ ...medley, bpm: 0 });
  refused({ ...medley, parts: medley.parts.slice(0, 1) });
  refused({ ...medley, parts: [medley.parts[0], { master: 'B', firstDownbeat: 0, from: 2, to: 2 }] });
});

test('a medley plays its parts in turn and repeats the first part exactly', () => {
  // 60 BPM in 1/4: a bar is one second, 100 frames at 100 Hz; a one-beat blend.
  const sampleRate = 100;
  const piece = (base) => ({ sampleRate, samples: [Float32Array.from({ length: 1000 }, (_, i) => base + i)] });
  const pieces = { A: piece(0), B: piece(10000) };
  const medley = { bpm: 60, beatsPerBar: 1, blendBeats: 1, parts: [{ master: 'A', firstDownbeat: 0, from: 2, to: 5 }, { master: 'B', firstDownbeat: 0.5, from: 3, to: 6 }] };
  const { samples: [out], frames } = lib.buildMedley(medley, pieces);
  // A from its start until the blend begins half a bar before bar 5.
  assert.strictEqual(out[0], 0);
  assert.strictEqual(out[449], 449);
  // B from half a bar after its bar 3 (frame 350) once the blend is over.
  assert.strictEqual(out[550], 10000 + 400);
  // Back into A at its bar 2: past the second blend, A's frames return.
  const back = 450 + 100 + (600 - 400) + 100; // A, blend, B up to half a bar before its bar 6, blend
  assert.strictEqual(out[back], 250);
  assert.strictEqual(frames, back + (1000 - 250));
  // The second pass of A is the first one, frame for frame.
  for (let i = 250; i < 449; i++) assert.strictEqual(out[back + i - 250], out[i]);
});
